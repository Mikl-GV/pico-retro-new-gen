// Полифазный 32768→48000. Фаза непрерывна между вызовами (как в GBA).
static uint32_t slt_gba_phase = 0;
static uint32_t slt_gba_resample(const int16_t* in, uint32_t nin, int16_t* out, uint32_t maxout) {
    uint32_t ph = slt_gba_phase;
    uint32_t o = 0;
    while (o < maxout) {
        uint32_t i = ph >> 16;
        if (i + SLT_POLY_TAPS / 2 >= nin) break;
        uint32_t f = ph & 0xFFFFu;
        uint32_t p = (f * SLT_POLY_PHASES) >> 16;
        if (p >= SLT_POLY_PHASES) p = SLT_POLY_PHASES - 1;
        const int16_t* h = slt_poly_h[p];
        int64_t a = 0;
        for (int k = 0; k < SLT_POLY_TAPS; k++) {
            int idx = (int)i - (SLT_POLY_TAPS / 2 - 1) + k;
            if (idx < 0) idx = 0;
            if ((uint32_t)idx >= nin) idx = (int)nin - 1;
            a += (int64_t)in[idx] * h[k];
        }
        int32_t s = (int32_t)(a >> 15);
        if (s > 32767) s = 32767;
        if (s < -32768) s = -32768;
        out[2 * o] = out[2 * o + 1] = (int16_t)s;
        o++;
        ph += 44739u;   // (32768<<16)/48000
    }
    if (ph >= ((uint64_t)nin << 16))
        slt_gba_phase = (uint32_t)(ph - ((uint64_t)nin << 16));
    else
        slt_gba_phase = 0;
    return o;
}

// ---------------------------------------------------------------------------
// Линейный ресемплер 44100→48000 (как NGP/fuse/bk: 16.16, шаг 60211).
// ---------------------------------------------------------------------------
static uint32_t slt_lin_phase = 0;
static uint32_t slt_lin_resample(const int16_t* in, uint32_t nin, int16_t* out, uint32_t maxout) {
    uint32_t ph = slt_lin_phase;
    uint32_t o = 0;
    while (o < maxout) {
        uint32_t i = ph >> 16;
        if (i + 1 >= nin) break;
        uint32_t f = ph & 0xFFFFu;
        int32_t m0 = in[i], m1 = in[i + 1];
        int32_t s = m0 + (int32_t)(((int64_t)(m1 - m0) * (int32_t)f) >> 16);
        if (s > 32767) s = 32767;
        if (s < -32768) s = -32768;
        out[2 * o] = out[2 * o + 1] = (int16_t)s;
        o++;
        ph += 60211u;   // (44100<<16)/48000
    }
    if (ph >= ((uint64_t)nin << 16))
        slt_lin_phase = (uint32_t)(ph - ((uint64_t)nin << 16));
    else
        slt_lin_phase = 0;
    return o;
}

