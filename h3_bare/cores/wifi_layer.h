#ifndef WIFI_LAYER_H
#define WIFI_LAYER_H

#include <stdint.h>

/* Отдельный слой WiFi (SDIO RTL8189FTV). Вызывается из пункта меню
   "Transfer": прошивка/калибровка идёт только когда пользователь вошёл
   в этот экран, а не при каждом старте. */

/* Инициализировать и запустить WiFi-слой: включить чип (WIFI_EN=PL7),
   инициализировать SDC1, SDIO-карту, загрузку FW, MAC, калибровку LCK,
   RX-тест. При успехе выставляет wifi_active=1. Возвращает 0 при успехе. */
int wifi_layer_start(void);

/* Уже был запущен в этой сессии? */
int wifi_layer_started(void);

/* Подключиться к выбранной сети из списка (UI «Transfer»): по индексу из
   буфера найденных сетей захватывает BSSID/channel как цель и запускает
   host-ассоциацию (JOINBSS). 0 = ассоциация подтверждена, иначе код
   (см. h3_wifi_join_ap; -4 — AuthResp не пришла). */
int wifi_layer_connect(int index);

/* Повторный скан эфира (UI «Transfer»): сбросить список найденных сетей и
   заново прогнать скан 13 каналов (h3_wifi_rf_rx_test), чтобы обновить
   список AP без перепрошивки. Возвращает 0 при успехе старта скана. */
int wifi_layer_rescan(void);

/* W.655 [пинг]: постоянный опрос сетевого RX в главном цикле. Принимает
   адрес (по DHCP ACK, при его отсутствии — по OFFER-фолбэку) и обрабатывает
   входящие ARP/ICMP (отвечает на ping). Возвращает число обработанных кадров. */
int wifi_layer_poll(void);

#endif /* WIFI_LAYER_H */