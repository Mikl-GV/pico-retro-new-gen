#ifndef USB_KBD_H
#define USB_KBD_H

#include <stdint.h>

int  usb_kbd_init(void);
int  usb_kbd_poll(void);       // меню: сканкод нажатия/повтора или 0
int  usb_kbd_get_raw(uint8_t* buf, int max_buf);   // текущее УДЕРЖИВАЕМОЕ состояние (скан-коды)
// Состояние без нового опроса USB (для ESC-удержания: emu_esc_hold).
int  usb_kbd_get_last(uint8_t* buf, int max_buf);
// модификаторы из первого байта boot-отчёта: LCtrl=1 LShift=2 LAlt=4 LGui=8 RCtrl=0x10 RShift=0x20 RAlt=0x40 RGui=0x80
uint8_t usb_kbd_get_mods(void);

// ---- Событийный слой (r0.32x) ----
// prev/cur отчётов -> фронты PRESS/RELEASE (очередь); удержание хранится
// как состояние (get_raw/get_last возвращают его непрерывно) — игра видит
// «клавиша держится», пока не наступит отпускание. Отпускание распознаётся
// двумя способами (проверено на железе: Low-Speed донгл I8 Pro НЕ шлёт
// пустой отчёт, а замолкает):
//   1) код исчез из нового отчёта (комбо/смена клавиш);
//   2) тишина потока отчётов дольше ~40 мс при зажатых клавишах (при
//      удержании отчёты продолжают идти — поэтому удержание не рвётся).
// Автоповтор — только для навигации в меню (usb_kbd_poll по своим порогам),
// в играх НЕ повторяем. Так же устроены драйверы Linux/Windows: клавиша
// «нажата», пока код в отчёте; разница — они видят ключевой апдейт
// устройства, а нам приходится доопределять отпускание по паузе в потоке.
#define KBD_EV_PRESS    1
#define KBD_EV_RELEASE  2
// Тишина потока отчётов при зажатых клавишах = отпускание (Low-Speed донгл)
#define KBD_IDLE_RELEASE_US 40000u

// Выход эмулятора для Low-Speed донгла (I8 Pro): удержание на нём ненадёжно
// (тишина и при удержании, и при отпускании) — поэтому ESC-выход сделан как
// 3 подряд нажатия ESC в окне ~0.7 с. Для остальных клавиатур эти вызовы
// всегда возвращают 0 (у них работает длинное удержание).
int  usb_kbd_esc3_pressed(void);   // 1, если Low-Speed ESC x3 (флаг потребляется)
void usb_kbd_esc3_reset(void);

// Тач GT911 (generic HID)
int  usb_touch_poll(int* x, int* y, int* pressed);
// Объединённый ввод для меню: клавиатура или тач(Enter)
int  usb_input_poll(void);
// Тач как джойстик для эмулятора
void usb_touch_joy(uint8_t* dir, uint8_t* fire);

// ---- Тачпад (boot mouse, напр. I8 Pro/Novatek) ----
void usb_pad_poll(void);   // накопление курсора из dx/dy
int  usb_pad_get_pos(int* x, int* y);     // позиция курсора, 0=нет тачпада

// ---- Sega-геймпад: помощь для подменю ----
// Фронт нажатия (биты, нажатые только что), без автоповтора
uint16_t usb_pad_just_pressed(void);
// Ждать полного отпускания геймпада (чтобы зажатая кнопка не «доехала» в подменю)
void usb_pad_wait_release(void);
// Ждать отпускания клавиатуры (чтобы зажатый Enter не «доехал» в подменю)
void usb_kbd_wait_release(void);
// Ждать отпускания ВСЕХ кнопок (клавиатура + Sega-геймпад) — на выходе из
// эмулятора: зажатая кнопка выхода (ESC / Start+Mode) не должна «доехать»
// в меню и прыгнуть курсор в первую строку. r0.204
void usb_wait_release_all(void);
// r0.222: перезапуск interrupt-IN цепочки клавиатуры (после эмулятора) —
// быстрые поллы могли рассинхронизировать ED; меню после выхода должно
// снова получать отчёты.
void usb_kbd_restart_intr(void);

// ---- Sega-геймпад: СВОЙ слой ввода (не через клавиатурные скан-коды) ----
// usb_pad_update(): один аппаратный скан (sega_pad_scan) не чаще раза в
// PAD_CACHE_US (2 мс), с антидребезгом PAD_DEBOUNCE_HITS. Повторные вызовы
// в том же окне возвращают закэшированное состояние (не дёргают чип
// пачками импульсов).
// ВАЖНО: эмуляторы (host-слои) вызывают sega_pad_scan() НАПРЯМУЮ раз в кадр
// — они идут МИМО кэша/антидребезга этого слоя и не обновляют g_pad_cache_t.
void usb_pad_update(void);
// Текущее стабильное состояние (биты как в sega_pad.h: UP=0x01...MODE=0x800)
uint16_t usb_pad_get(void);
// Биты, нажатые ТОЛЬКО что (фронт 0→1 после стабилизации)
uint16_t usb_pad_edge(void);

// ---- Sega-геймпад: константы автоповтора ----
#define PAD_REPEAT_DELAY_US 400000   // 0,4 с до первого повтора
#define PAD_REPEAT_RATE_US  200000   // 5 шагов/с при удержании

#endif