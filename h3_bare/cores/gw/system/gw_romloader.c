// Порт под H3 (pico-retro-new-gen): ROM приходит от host уже в памяти
// (ROM_BUF, из rom_browser load_rom -> emu_run_gw(rom,size)). Вместо чтения
// с SD через util_sd.h указываем GW_ROM прямо на входной буфер и выставляем
// указатели на секции .gwm — копирование не нужно (buffer остаётся живым
// на время сессии, кэш слит в load_rom). Файловый слой/превью убраны.

#include <string.h>
#include <stdlib.h>
#include <stdio.h>
#include "gw_type_defs.h"
#include "gw_system.h"
#include "gw_romloader.h"

uint8_t *GW_ROM;

uint16_t *gw_background_pal = NULL;
uint16_t *gw_background = NULL;
uint8_t *gw_segments = NULL;
uint16_t *gw_segments_x = NULL;
uint16_t *gw_segments_y = NULL;
uint16_t *gw_segments_width = NULL;
uint16_t *gw_segments_height = NULL;
uint32_t *gw_segments_offset = NULL;
uint8_t *gw_program = NULL;
uint8_t *gw_melody = NULL;
uint32_t *gw_keyboard = NULL;

gwromheader_t gw_head;

// Разбор заголовка (первые ROM_HEADER_SIZE=150 байт) от начала буфера.
bool gw_romloader(const uint8_t* rom, uint32_t size)
{
   if (!rom || size < ROM_HEADER_SIZE)
   {
      printf("gw_romloader: bad rom size=%u\n", (unsigned)size);
      return false;
   }

   // заголовок всегда в начале
   memcpy(&gw_head, rom, sizeof(gw_head));

   // формат от LCD-Game-Shrinker: cpu_name начинается с "SM5"
   if (memcmp(gw_head.cpu_name, ROM_CPU_SM510, 3) != 0 &&
       memcmp(gw_head.cpu_name, ROM_CPU_SM5A, 3) != 0 &&
       memcmp(gw_head.cpu_name, ROM_CPU_SM500, 3) != 0)
   {
      printf("gw_romloader: unknown ROM format cpu='%.5s'\n", gw_head.cpu_name);
      return false;
   }

   // максимальный фрейм данных = конец последней секции (keyboard)
   uint32_t end = gw_head.keyboard + gw_head.keyboard_size;
   if (end < sizeof(gw_head) || end > size)
   {
      printf("gw_romloader: size mismatch, need=%u have=%u\n", (unsigned)end, (unsigned)size);
      return false;
   }

   GW_ROM = (uint8_t*)rom;

   if (gw_head.background_pixel_size != 0 && gw_head.background_palette < size &&
       gw_head.background_pixel < size)
   {
      gw_background_pal = (uint16_t*)&GW_ROM[gw_head.background_palette];
      gw_background     = (uint16_t*)&GW_ROM[gw_head.background_pixel];
   }

   gw_segments        = (uint8_t *)&GW_ROM[gw_head.segments_pixel];
   gw_segments_x      = (uint16_t*)&GW_ROM[gw_head.segments_x];
   gw_segments_y      = (uint16_t*)&GW_ROM[gw_head.segments_y];
   gw_segments_width  = (uint16_t*)&GW_ROM[gw_head.segments_width];
   gw_segments_height = (uint16_t*)&GW_ROM[gw_head.segments_height];
   gw_segments_offset = (uint32_t*)&GW_ROM[gw_head.segments_offset];

   gw_program = (uint8_t *)&GW_ROM[gw_head.program];

   if (gw_head.melody_size != 0 && gw_head.melody < size)
      gw_melody = (uint8_t *)&GW_ROM[gw_head.melody];
   else
      gw_melody = NULL;

   gw_keyboard = (uint32_t *)&GW_ROM[gw_head.keyboard];

   printf("gw_romloader: cpu='%.5s' sig='%.8s' end=%u size=%u prog=%u mel=%u\n",
          gw_head.cpu_name, gw_head.rom_signature,
          (unsigned)end, (unsigned)size,
          (unsigned)gw_head.program,
          (unsigned)gw_head.melody_size);
   return true;
}