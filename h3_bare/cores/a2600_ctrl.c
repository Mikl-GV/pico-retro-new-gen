static int hexval(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

static int contains_ci(const char* s, const char* sub) {
    if (!s || !sub) return 0;
    size_t n = strlen(sub);
    if (!n) return 0;
    for (; *s; s++) {
        size_t i = 0;
        while (i < n && s[i]) {
            char a = s[i], b = sub[i];
            if (a >= 'a' && a <= 'z') a = (char)(a - 32);
            if (b >= 'a' && b <= 'z') b = (char)(b - 32);
            if (a != b) break;
            i++;
        }
        if (i == n) return 1;
    }
    return 0;
}

// Known paddle titles missing in the 2014 property database
// (the DB leaves Controller.* empty for them).
static const char* const a26_paddle_names[] = {
    "PONG", "PINBALL", "BREAKOUT", "WARLORDS", "KABOOM",
    "CIRCUS ATARI", "NIGHT DRIVER", "STREET RACER",
    "DEMONS TO DIAMONDS", "PADDLE"
};

int a2600_ctrl_lookup(const char* md5hex, const char* rom_name,
                     int* left, int* right, int* swap) {
    *left = A26C_JOY;
    *right = A26C_JOY;
    *swap = 0;

    if (md5hex && strlen(md5hex) == 32) {
        unsigned char md5[16];
        int ok = 1;
        for (int i = 0; i < 16; i++) {
            int hi = hexval(md5hex[i * 2]);
            int lo = hexval(md5hex[i * 2 + 1]);
            if (hi < 0 || lo < 0) { ok = 0; break; }
            md5[i] = (unsigned char)(hi * 16 + lo);
        }
        if (ok) {
            for (unsigned i = 0; i < sizeof(a26_ctrl_tbl) / sizeof(a26_ctrl_tbl[0]); i++) {
                if (memcmp(a26_ctrl_tbl[i].md5, md5, 16) == 0) {
                    *left = a26_ctrl_tbl[i].l;
                    *right = a26_ctrl_tbl[i].r;
                    *swap = a26_ctrl_tbl[i].swap;
                    return 1;
                }
            }
        }
    }

    for (unsigned i = 0; i < sizeof(a26_paddle_names) / sizeof(a26_paddle_names[0]); i++) {
        if (contains_ci(rom_name, a26_paddle_names[i])) {
            *left = A26C_PADDLES;
            return 1;
        }
    }
    return 0;
}
