// Вывести один символ (x,y = пиксель левого верхнего угла)
void fb_putchar(int x, int y, char c, uint32_t color) {
    fb_mark_dirty(x, y, 8, 8);
    if (c < 0x20 || c > 0x7F) c = '.';
    const uint8_t* glyph = font8x8[c - 0x20];
    volatile uint32_t* fb = (volatile uint32_t*)s_fb_draw;
    for (int row = 0; row < 8; row++) {
        uint8_t bits = (c == '_' && row == 7) ? 0xFF : glyph[row];
        for (int col = 0; col < 8; col++) {
            int px = x + col;
            int py = y + row;
            if (px >= 0 && px < FB_W && py >= 0 && py < FB_H) {
                if (bits & (0x80 >> col))
                    fb[py * FB_W + px] = color;
            }
        }
    }
}

// Вывести строку (x,y = пиксель первой буквы)
void fb_puts(int x, int y, const char* s, uint32_t color) {
    while (*s) {
        fb_putchar(x, y, *s, color);
        x += 10;
        if (x + 10 > FB_W) { x = 0; y += 10; }
        s++;
    }
}

// Залить прямоугольник
void fb_fill_rect(int x, int y, int w, int h, uint32_t color) {
    volatile uint32_t* fb = (volatile uint32_t*)s_fb_draw;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > FB_W) w = FB_W - x;
    if (y + h > FB_H) h = FB_H - y;
if (w <= 0 || h <= 0) return;
    fb_mark_dirty(x, y, w, h);
    for (int yy = y; yy < y + h; yy++)
        for (int xx = x; xx < x + w; xx++)
            fb[yy * FB_W + xx] = color;
}

// Масштабированный символ scale=1..4
static void fb_putchar_s(int x, int y, char c, int scale, uint32_t color) {
    fb_mark_dirty(x, y, 8 * scale, 8 * scale);
    if (c < 0x20 || c > 0x7F) c = '.';
    const uint8_t* glyph = font8x8[c - 0x20];
    volatile uint32_t* fb = (volatile uint32_t*)s_fb_draw;
    for (int row = 0; row < 8; row++) {
        uint8_t bits = (c == '_' && row == 7) ? 0xFF : glyph[row];
        for (int col = 0; col < 8; col++) {
            if (!(bits & (0x80 >> col))) continue;
            for (int dy = 0; dy < scale; dy++)
                for (int dx = 0; dx < scale; dx++) {
                    int px = x + col * scale + dx;
                    int py = y + row * scale + dy;
                    if (px >= 0 && px < FB_W && py >= 0 && py < FB_H)
                        fb[py * FB_W + px] = color;
                }
        }
    }
}

// Масштабированная строка. Возвращает новую x-координату.
int fb_puts_s(int x, int y, const char* s, int scale, uint32_t color) {
    int adv = 8 * scale + 2 * scale;
    while (*s) {
        fb_putchar_s(x, y, *s, scale, color);
        x += adv;
        s++;
    }
    return x;
}

// --- Масштаб 1.5x (12px) — «немного крупнее» без целого 2x ----
// Глиф 8x8 масштабируется чередованием 2/1 пиксель по обеим осям:
// суммарно 12x12, шаг строки 15px ((8+2)*1.5).
static const int s15_off[8] = { 0, 2, 3, 5, 6, 8, 9, 11 };
static const int s15_len[8] = { 2, 1, 2, 1, 2, 1, 2, 1 };
static void fb_putchar_s15(int x, int y, char c, uint32_t color) {
    fb_mark_dirty(x, y, 15, 12);
    if (c < 0x20 || c > 0x7F) c = '.';
    const uint8_t* glyph = font8x8[c - 0x20];
    volatile uint32_t* fb = (volatile uint32_t*)s_fb_draw;
    for (int row = 0; row < 8; row++) {
        uint8_t bits = (c == '_' && row == 7) ? 0xFF : glyph[row];
        for (int col = 0; col < 8; col++) {
            if (!(bits & (0x80 >> col))) continue;
            for (int yy = 0; yy < s15_len[row]; yy++)
                for (int xx = 0; xx < s15_len[col]; xx++) {
                    int px = x + s15_off[col] + xx;
                    int py = y + s15_off[row] + yy;
                    if (px >= 0 && px < FB_W && py >= 0 && py < FB_H)
                        fb[py * FB_W + px] = color;
                }
        }
    }
}
int fb_puts_s15(int x, int y, const char* s, uint32_t color) {
    while (*s) {
        fb_putchar_s15(x, y, *s, color);
        x += 15;
        s++;
    }
    return x;
}

void fb_pixel(int x, int y, uint32_t color) {
    if (x < 0 || x >= FB_W || y < 0 || y >= FB_H) return;
    fb_mark_dirty(x, y, 1, 1);
    volatile uint32_t* fb = (volatile uint32_t*)s_fb_draw;
    fb[y * FB_W + x] = color;
}

// ---- детерминированное звёздное небо ----
static uint32_t s_seed;

static uint32_t s_rand(void) {
    s_seed = s_seed * 1664525u + 1013904223u;
    return s_seed;
}

void fb_draw_stars(void) {
    fb_clear();
    s_seed = 0x2C92714B;
    const uint32_t cols[5] = { 0x00202028, 0x00383844, 0x00585868, 0x00808090, 0x00C0C0D0 };
    for (int i = 0; i < 140; i++) {
        int x = (int)((s_rand() >> 16) % 1024u);
        int y = (int)((s_rand() >> 16) % 600u);
        uint32_t c = cols[(s_rand() >> 29) & 3];
        fb_pixel(x, y, c);
        if ((s_rand() & 0xFF) < 10) {
            fb_pixel(x + 1, y, c);
            fb_pixel(x, y + 1, c);
            fb_pixel(x + 1, y + 1, c);
        }
    }
}
void fb_text_center(const char* s, int y, int scale, uint32_t color) {
    int len = 0;
    while (s[len]) len++;
    int w = len * (8 * scale + 2 * scale) - 2 * scale;
    int x = (FB_W - w) / 2;
    if (x < 0) x = 0;
    fb_puts_s(x, y, s, scale, color);
}

// Очистить экран в чёрный
void fb_clear(void) {
    fb_dirty_all();
    volatile uint32_t* fb = (volatile uint32_t*)s_fb_draw;
    for (int i = 0; i < FB_W * FB_H; i++) fb[i] = 0;
}

// ---- r1159 (E14): dirty-зоны фреймбуфера ----
// fb_flush чистит D-cache только по записанной области (для кадров, собранных
// emu_scale/emu_scale_int), а не все 2.4 МБ. Если кадр писался не скейлером
// (меню, хосты с прямой записью в FB), остаётся полный флеш — безопасный
// фолбэк, поведение r1158 сохраняется.
static int g_dx0, g_dy0, g_dx1, g_dy1;   // [x0,x1) x [y0,y1), пиксели
static int g_dirty_any = 0;
static int g_scaled_frame = 0;

void fb_mark_dirty(int x, int y, int w, int h) {
    if (w <= 0 || h <= 0) return;
    int x1 = x + w, y1 = y + h;
    if (x < 0) x = 0;
    if (y < 0) y = 0;
    if (x1 > FB_W) x1 = FB_W;
    if (y1 > FB_H) y1 = FB_H;
    if (x >= x1 || y >= y1) return;
    if (!g_dirty_any) {
        g_dx0 = x; g_dy0 = y; g_dx1 = x1; g_dy1 = y1; g_dirty_any = 1;
        return;
    }
    if (x < g_dx0) g_dx0 = x;
    if (y < g_dy0) g_dy0 = y;
    if (x1 > g_dx1) g_dx1 = x1;
    if (y1 > g_dy1) g_dy1 = y1;
}

void fb_dirty_all(void) { fb_mark_dirty(0, 0, FB_W, FB_H); }

// Скейлер сообщает: кадр целиком перерисован в отмеченном прямоугольнике.
void fb_frame_scaled(void) { g_scaled_frame = 1; }

// Clean D-cache для фреймбуфера (DE2 читает через DMA, а CPU пишет через
// write-back cache). Без этого на экране мусор/чёрный экран.
// MVA-clean по 32-байтным линиям — проверенный рабочий вариант.
// (Set/Way-clean-all тут не годится: на этом железе чистил не те линии и
//  картинка рассыпалась.)
void fb_flush(void) {
    int x0 = 0, y0 = 0, x1 = FB_W, y1 = FB_H;
    if (g_scaled_frame && g_dirty_any) {
        x0 = g_dx0 & ~7;                 // 32-байтная линия = 8 пикселей
        y0 = g_dy0;
        x1 = (g_dx1 + 7) & ~7;
        if (x1 > FB_W) x1 = FB_W;
        y1 = g_dy1;
    }
    for (int y = y0; y < y1; y++) {
        uint32_t addr = (s_fb_draw + ((uint32_t)y * FB_W + (uint32_t)x0) * 4u) & ~0x1Fu;
        uint32_t end  = s_fb_draw + ((uint32_t)y * FB_W + (uint32_t)x1) * 4u;
        for (; addr < end; addr += 32) {
            __asm volatile("mcr p15, 0, %0, c7, c10, 1" :: "r"(addr)); // clean MVA
        }
    }
    g_dirty_any = 0;
    g_scaled_frame = 0;
    __asm volatile("dsb" ::: "memory");
    // r1183: кадр собран и вычищен — при включённой опции отдаём его DE2 и
    // переключаем рисование во второй буфер. Адрес защёлкнется по vblank;
    // следующий композит придёт уже отсюда, поэтому кадр цельный.
    if (s_flip_on) {
        uint32_t shown = s_fb_draw;
        h3_de2_set_ui_addr(shown);
        s_fb_draw = (shown == FB_ADDR) ? FB_ADDR_BACK : FB_ADDR;
    }
}