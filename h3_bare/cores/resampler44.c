uint32_t rs44fs_stereo(uint32_t* phase, int16_t* tail,
                       const int16_t* in, uint32_t in_n,
                       int16_t* out, uint32_t max_out)
{
    uint32_t ph = *phase;
    uint32_t o = 0;
    while (o < max_out) {
        uint32_t i = ph >> 16;
        if (i >= in_n) break;
        uint32_t f = ph & 0xFFFFu;
        uint32_t p = (f * RS44_PHASES) >> 16;
        if (p >= RS44_PHASES) p = RS44_PHASES - 1;
        const int16_t* h = rs44_poly_h[p];
        int64_t al = 0, ar = 0;
        for (int k = 0; k < RS44_TAPS; k++) {
            int idx = (int)i - (RS44_TAPS / 2 - 1) + k;
            int16_t l, r;
            if (idx < 0) { l = tail[0]; r = tail[1]; }
            else if ((uint32_t)idx >= in_n) { l = in[2 * (in_n - 1)]; r = in[2 * (in_n - 1) + 1]; }
            else { l = in[2 * idx]; r = in[2 * idx + 1]; }
            al += (int64_t)l * h[k];
            ar += (int64_t)r * h[k];
        }
        out[2 * o]     = (int16_t)(int32_t)(al >> 15);
        out[2 * o + 1] = (int16_t)(int32_t)(ar >> 15);
        o++;
        ph += RS44_STEP;
    }
    if (ph >= ((uint64_t)in_n << 16))
        *phase = (uint32_t)(ph - ((uint64_t)in_n << 16));
    else
        *phase = ph;
    if (in_n > 0) { tail[0] = in[2 * (in_n - 1)]; tail[1] = in[2 * (in_n - 1) + 1]; }
    return o;
}

uint32_t rs44fs_mono(uint32_t* phase, int16_t* tail,
                     const int16_t* in, uint32_t in_n,
                     int16_t* out, uint32_t max_out)
{
    uint32_t ph = *phase;
    uint32_t o = 0;
    while (o < max_out) {
        uint32_t i = ph >> 16;
        if (i >= in_n) break;
        uint32_t f = ph & 0xFFFFu;
        uint32_t p = (f * RS44_PHASES) >> 16;
        if (p >= RS44_PHASES) p = RS44_PHASES - 1;
        const int16_t* h = rs44_poly_h[p];
        int64_t a = 0;
        for (int k = 0; k < RS44_TAPS; k++) {
            int idx = (int)i - (RS44_TAPS / 2 - 1) + k;
            int16_t s;
            if (idx < 0) s = *tail;
            else if ((uint32_t)idx >= in_n) s = in[in_n - 1];
            else s = in[idx];
            a += (int64_t)s * h[k];
        }
        int16_t s = (int16_t)(int32_t)(a >> 15);
        out[2 * o]     = s;
        out[2 * o + 1] = s;
        o++;
        ph += RS44_STEP;
    }
    if (ph >= ((uint64_t)in_n << 16))
        *phase = (uint32_t)(ph - ((uint64_t)in_n << 16));
    else
        *phase = ph;
    if (in_n > 0) *tail = in[in_n - 1];
    return o;
}